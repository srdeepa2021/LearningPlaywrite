// Identifiers - names used to identify variables, functions, etc.
// Variables - storage locations for data
// Operators - symbols that perform operations on operands (e.g., +, -, *, /)   

// Rules of Identifiers:
// 1. Must start with a letter, underscore (_), or dollar sign ($)
// 2. Can contain letters, digits, underscores, or dollar signs
// 3. Cannot be a reserved keyword (e.g., var, function, if, else)
// 4. Case-sensitive (e.g., myVar and myvar are different identifiers)
// 5. Should not start with a digit (e.g., 1var is invalid)
